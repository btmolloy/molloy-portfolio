import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const rootDirectory = path.resolve(scriptDirectory, "..");
const dataPath = path.join(rootDirectory, "data", "projects.js");
const templatePath = path.join(rootDirectory, "project.html");
const projectsDirectory = path.join(rootDirectory, "projects");

const context = { window: {} };
vm.runInNewContext(fs.readFileSync(dataPath, "utf8"), context, { filename: dataPath });

const allProjects = context.window.PORTFOLIO_PROJECTS;
if (!Array.isArray(allProjects) || !allProjects.length) {
  throw new Error("data/projects.js did not expose any projects.");
}
const projects = allProjects.filter((project) => project.published === true);
if (!projects.length) {
  throw new Error("data/projects.js did not expose any published projects.");
}

const template = fs.readFileSync(templatePath, "utf8");
const escapeAttribute = (value) => String(value ?? "")
  .replace(/&/g, "&amp;")
  .replace(/\"/g, "&quot;")
  .replace(/</g, "&lt;")
  .replace(/>/g, "&gt;");

fs.mkdirSync(projectsDirectory, { recursive: true });
const publishedIds = new Set(projects.map((project) => project.id));
for (const entry of fs.readdirSync(projectsDirectory, { withFileTypes: true })) {
  if (!entry.isDirectory() || publishedIds.has(entry.name)) continue;
  const generatedPage = path.join(projectsDirectory, entry.name, "index.html");
  if (!fs.existsSync(generatedPage)) continue;
  const generatedHtml = fs.readFileSync(generatedPage, "utf8");
  if (generatedHtml.includes("Generated by scripts/build-project-pages.mjs")) {
    fs.rmSync(path.join(projectsDirectory, entry.name), { recursive: true, force: true });
  }
}

for (const project of projects) {
  if (!project.id || !/^[a-z0-9-]+$/.test(project.id)) {
    throw new Error(`Project id must be a URL-safe slug: ${project.id || "(missing)"}`);
  }

  const title = `${project.title} — Benjamin Molloy`;
  const description = project.summary || project.problem || "A Benjamin Molloy project case study.";
  const canonical = `https://www.molloy.info/projects/${project.id}/`;
  const outputDirectory = path.join(projectsDirectory, project.id);
  const outputPath = path.join(outputDirectory, "index.html");

  const output = template
    .replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/build-project-pages.mjs. Edit project.html or data/projects.js instead. -->")
    .replace("<title>Project — Benjamin Molloy</title>", `<title>${escapeAttribute(title)}</title>`)
    .replace('content="A Benjamin Molloy project case study."', `content="${escapeAttribute(description)}"`)
    .replace('href="https://www.molloy.info/project.html"', `href="${escapeAttribute(canonical)}"`)
    .replace('<body data-page="projects">', `<body data-page="projects" data-project-id="${escapeAttribute(project.id)}">`)
    .replaceAll('href="assets/', 'href="/assets/')
    .replaceAll('src="assets/', 'src="/assets/')
    .replaceAll('src="data/', 'src="/data/');

  fs.mkdirSync(outputDirectory, { recursive: true });
  fs.writeFileSync(outputPath, output);
}

const sitemapUrls = [
  "https://www.molloy.info/",
  "https://www.molloy.info/projects/",
  ...projects.map((project) => `https://www.molloy.info/projects/${project.id}/`)
];
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemapUrls.map((url) => `  <url><loc>${url}</loc></url>`).join("\n")}
</urlset>
`;
fs.writeFileSync(path.join(rootDirectory, "sitemap.xml"), sitemap);

console.log(`Generated ${projects.length} project case-study routes and sitemap.xml.`);
